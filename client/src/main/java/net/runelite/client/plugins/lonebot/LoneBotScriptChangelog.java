    public static List<Entry> entries() {
        return Collections.unmodifiableList(ENTRIES);
    }

    public static List<Entry> forScript(String scriptId) {
        if (scriptId == null) {
            return List.of();
        }
        String id = scriptId.toLowerCase(Locale.ROOT);
        return ENTRIES.stream()
                .filter(e -> id.equals(e.scriptId))
                .collect(Collectors.toList());
    }

    /** Nieuwste samenvatting voor Scripts-tab (of {@code null}). */
    public static String latestSummary(String scriptId) {
        List<Entry> list = forScript(scriptId);
        return list.isEmpty() ? null : list.get(0).summary;
    }

    public static String asHtml() {
        StringBuilder sb = new StringBuilder();
        sb.append("<div style='margin:16px 0 8px 0;color:#f0a050;'><b>Scripts</b></div>");
        String lastName = "";
        for (Entry e : ENTRIES) {
            if (!e.scriptName.equals(lastName)) {
                lastName = e.scriptName;
                sb.append("<div style='margin:10px 0 4px 0;color:#c8d4e8;'><b>")
                        .append(escape(e.scriptName)).append("</b></div>");
            }
            sb.append("<div style='margin:0 0 8px 12px;'>")
                    .append("<b style='color:#8ec8ff;'>v").append(escape(e.version)).append("</b>")
                    .append(" <span style='color:#9aa3b5;'>").append(escape(e.date)).append("</span><br>")
                    .append(escape(e.summary))
                    .append("</div>");
        }
        return sb.toString();
    }

    private static String escape(String s) {
        if (s == null) {
            return "";
        }
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    }
