    public static String describe(int id) {
        if (id < 0) {
            return "IDLE";
        }
        String n = nameOf(id);
        return n != null ? n + "(" + id + ")" : "UNKNOWN(" + id + ")";
    }

    public static boolean isWoodcutting(int id) {
        String n = nameOf(id);
        if (n != null) {
            return n.startsWith("WOODCUTTING_") || n.contains("WOODCUTTING");
        }
        // fallback ranges buiten named dump
        return (id >= 867 && id <= 879) || (id >= 3282 && id <= 3305)
                || id == 8324 || id == 10073;
    }

    public static boolean isFiremaking(int id) {
        return id == FIREMAKING;
    }

    public static boolean isBonfireOrForester(int id) {
        String n = nameOf(id);
        if (n != null && n.startsWith("FIREMAKING_FORESTERS_CAMPFIRE")) {
            return true;
        }
        return id >= FIREMAKING_FORESTERS_CAMPFIRE_ARCTIC_PINE
                && id <= FIREMAKING_FORESTERS_CAMPFIRE_YEW;
    }

    public static boolean isFiremakingRelated(int id) {
        return isFiremaking(id) || isBonfireOrForester(id);
    }

